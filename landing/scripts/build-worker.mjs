// Packs the built page into one Cloudflare Worker (deploy/worker.js) for zifidit.com.
// The Worker serves the page and handles POST /api/waitlist with the D1 binding `DB`.
// Run after `npm run build`:  npm run build:worker
import { readFileSync, writeFileSync } from "node:fs";

let html = readFileSync("dist/index.html", "utf8");
// Fonts come from Google Fonts here so the Worker stays a single small file.
html = html.replace(/@font-face\{[^}]*\}/g, "");
html = html.replace("<head>", '<head><link rel="preconnect" href="https://fonts.googleapis.com"><link rel="preconnect" href="https://fonts.gstatic.com" crossorigin><link rel="stylesheet" href="https://fonts.googleapis.com/css2?family=Alexandria:wght@300..800&family=Readex+Pro:wght@300..700&display=swap">');
html = html.replaceAll('"Alexandria Variable", ', "").replaceAll('"Readex Pro Variable", ', "");
html = html.replace(/<meta property="og:image[^>]*>/g, "").replace("summary_large_image", "summary");

const fav = readFileSync("public/favicon.svg", "utf8");
const robots = readFileSync("public/robots.txt", "utf8");

const worker = `// GENERATED by scripts/build-worker.mjs — do not edit by hand.
const HTML = ${JSON.stringify(html)};
const FAVICON = ${JSON.stringify(fav)};
const ROBOTS = ${JSON.stringify(robots)};
const SEC = {
  "X-Content-Type-Options": "nosniff",
  "Referrer-Policy": "strict-origin-when-cross-origin",
  "X-Frame-Options": "DENY",
  "Permissions-Policy": "camera=(), microphone=(), geolocation=()",
};
const EMAIL_RE = /^[^\\s@]+@[^\\s@]+\\.[^\\s@]{2,}$/;
const clean = (v, max) => String(v ?? "").replace(/[\\u0000-\\u001f\\u007f]/g, " ").trim().slice(0, max);
const json = (body, status = 200) => new Response(JSON.stringify(body), { status, headers: { ...SEC, "Content-Type": "application/json; charset=utf-8", "Cache-Control": "no-store" } });

async function waitlist(request, env) {
  if (request.method !== "POST") return json({ error: "method_not_allowed" }, 405);
  if (!env.DB) return json({ error: "not_configured" }, 503);
  let body;
  try { body = await request.json(); } catch { return json({ error: "bad_request" }, 400); }
  if (clean(body.website, 200)) return json({ ok: true });
  const email = clean(body.email, 160).toLowerCase();
  if (!EMAIL_RE.test(email)) return json({ error: "invalid_email" }, 400);
  const utm = body.utm && typeof body.utm === "object" ? body.utm : {};
  try {
    const r = await env.DB.prepare(
      "INSERT OR IGNORE INTO waitlist (email, utm_source, utm_medium, utm_campaign, referrer, country, created_at) VALUES (?1, ?2, ?3, ?4, ?5, ?6, ?7)",
    ).bind(email, clean(utm.source, 100), clean(utm.medium, 100), clean(utm.campaign, 100), clean(body.referrer, 300), clean(request.cf?.country, 8), new Date().toISOString()).run();
    const row = await env.DB.prepare("SELECT id FROM waitlist WHERE email = ?1").bind(email).first();
    return json({ ok: true, already: r.meta.changes === 0, position: row?.id ?? null });
  } catch (err) {
    console.error("waitlist: d1 error", err);
    return json({ error: "storage_failed" }, 502);
  }
}

export default {
  async fetch(request, env) {
    const url = new URL(request.url);
    if (url.hostname.startsWith("www.")) { url.hostname = url.hostname.slice(4); return Response.redirect(url.toString(), 301); }
    switch (url.pathname) {
      case "/api/waitlist": return waitlist(request, env);
      case "/favicon.svg": return new Response(FAVICON, { headers: { ...SEC, "Content-Type": "image/svg+xml", "Cache-Control": "public, max-age=86400" } });
      case "/robots.txt": return new Response(ROBOTS, { headers: { "Content-Type": "text/plain; charset=utf-8" } });
      case "/": case "/index.html":
        return new Response(HTML, { headers: { ...SEC, "Content-Type": "text/html; charset=utf-8", "Cache-Control": "public, max-age=300" } });
      default: return Response.redirect(url.origin + "/", 302);
    }
  },
};
`;
writeFileSync("deploy/worker.js", worker);
console.log(`deploy/worker.js ${(worker.length / 1024).toFixed(1)} KB`);
